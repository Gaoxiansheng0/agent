const DICTS: Record<Lang, Dict> = { en, 'zh-Hans': zhHans, 'zh-Hant': zhHant, es }

/** Phone language -> one of ours. Taiwan, Hong Kong and Macau default to Traditional Chinese. */
export function deviceLang(): Lang {
  const loc = getLocales()[0]
  if (!loc) return 'en'
  if (loc.languageCode === 'zh') {
    const hant = loc.languageScriptCode === 'Hant' || ['TW', 'HK', 'MO'].includes(loc.regionCode ?? '')
    return hant ? 'zh-Hant' : 'zh-Hans'
  }
  return loc.languageCode === 'es' ? 'es' : 'en'
}

type Vars = Record<string, string | number>
export type T = (key: Key, vars?: Vars) => string

function translate(lang: Lang, key: Key, vars?: Vars) {
  const d = DICTS[lang]
  const one = vars?.n === 1 && (`${key}_one` as Key) in d ? d[`${key}_one` as Key] : undefined
  const text = one ?? d[key] ?? en[key] ?? key
  return vars ? text.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : text
}

type I18n = { lang: Lang; setting: Lang | 'system'; setSetting: (v: Lang | 'system') => void; t: T }
const Ctx = createContext<I18n | null>(null)
const KEY = 'pearlkin:lang'

export function I18nProvider({ children }: { children: ReactNode }) {
  const [setting, setSettingState] = useState<Lang | 'system'>('system')
  useEffect(() => {
    AsyncStorage.getItem(KEY).then(v => { if (v && (v === 'system' || v in DICTS)) setSettingState(v as Lang | 'system') }).catch(() => {})
  }, [])
  const lang = setting === 'system' ? deviceLang() : setting
  const value: I18n = {
    lang, setting,
    setSetting: v => { setSettingState(v); AsyncStorage.setItem(KEY, v) },
    t: (key, vars) => translate(lang, key, vars),
  }
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n() {
  const c = useContext(Ctx)
  if (!c) throw new Error('useI18n outside I18nProvider')
  return c
}

/** A rule-pack message in the user's language; English (the reviewed source) when there's no translation yet. */
export const msg = (pack: Pack, lang: Lang, key: string) => pack.translations?.[lang]?.[key] || pack.messages[key] || key

/** Ingredient function labels ("exfoliant") come from the rule pack in English. */
export const fnLabel = (t: T, f: string) => (`fn.${f}` in en ? t(`fn.${f}` as Key) : f)

/** Admin-edited text (questionnaire) in the user's language, English when that language is missing. */
export const loc = (l: { en: string } & Partial<Record<Lang, string>>, lang: Lang) => l[lang] || l.en
